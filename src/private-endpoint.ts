/** Convert host-generated secrets to a single URL-safe path segment without
 * changing their bytes/entropy. Existing URL-safe endpoint credentials stay stable. */
export function secretPathSegment(value: string): string {
  if (value.length >= 32 && value.length <= 128 && !/[^a-zA-Z0-9_-]/.test(value)) return value;

  // Render generateValue produces canonical, padded Base64 for 32 random bytes.
  // Buffer's decoder is permissive, so check the exact spelling before accepting it.
  if (value.length === 44 && /^[a-zA-Z0-9+/]{43}=$/.test(value)) {
    const bytes = Buffer.from(value, 'base64');
    if (bytes.length === 32 && bytes.toString('base64') === value)
      return bytes.toString('base64url');
  }
  throw new Error(
    'TWMCP_SECRET must be a cryptographically random value: 32–128 URL-safe characters or a Base64-encoded 256-bit secret generated by Render.',
  );
}
